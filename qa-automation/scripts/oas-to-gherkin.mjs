/**
 * Spec → Gherkin: reads a slim OpenAPI JSON slice and emits a technical feature file.
 * Usage: node scripts/oas-to-gherkin.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const SPEC_PATH = path.join(root, 'specs', 'control-room', 'contacts.openapi.json');
const OUT_PATH = path.join(root, 'features', 'api', 'control_room_contacts_create.feature');

function getExample(operation) {
  const content = operation.requestBody?.content?.['application/json'];
  return content?.example ?? {};
}

function emitFeature(oaspec) {
  const lines = [];
  const title = oaspec.info?.title || 'API (generated from OpenAPI)';
  lines.push(`Feature: ${title}`);
  lines.push('  Generated by scripts/oas-to-gherkin.mjs — do not hand-edit as source of truth.');
  lines.push('  Change specs/control-room/contacts.openapi.json and re-run: npm run oas:gherkin');
  lines.push('');

  for (const [apiPath, pathItem] of Object.entries(oaspec.paths || {})) {
    for (const [method, operation] of Object.entries(pathItem)) {
      if (typeof operation !== 'object' || !operation.responses) continue;

      const summary = operation.summary || `${method.toUpperCase()} ${apiPath}`;
      const example = getExample(operation);
      const exampleJson = JSON.stringify(example);

      // Happy path (prefer 200)
      if (operation.responses['200']) {
        lines.push('  @contact @api @control-room @smoke');
        lines.push(`  Scenario: ${summary} leading to 200`);
        lines.push('    Given the API base URL is configured');
        lines.push('    And a valid Authorization bearer token is configured');
        lines.push('    And request body is the OpenAPI example for this operation');
        lines.push(`    When request operation is "${method.toUpperCase()}"`);
        lines.push(`    And request path is "${apiPath}"`);
        lines.push('    And the request is sent');
        lines.push('    Then response status is 200');
        lines.push('    And response JSON has non-empty field "id"');
        lines.push('    And response JSON field "firstName" equals the prepared request field "firstName"');
        lines.push('    And response JSON field "email" equals the prepared request field "email"');
        lines.push(`    # Spec example used as base payload: ${exampleJson}`);
        lines.push('');
      }

      // Validation (400) — remove required email when present in schema
      if (operation.responses['400']) {
        lines.push('  @contact @api @control-room');
        lines.push(`  Scenario: ${summary} missing email leading to 400`);
        lines.push('    Given the API base URL is configured');
        lines.push('    And a valid Authorization bearer token is configured');
        lines.push('    And request body is the OpenAPI example without field "email"');
        lines.push(`    When request operation is "${method.toUpperCase()}"`);
        lines.push(`    And request path is "${apiPath}"`);
        lines.push('    And the request is sent');
        lines.push('    Then response status is 400');
        lines.push('');
      }

      // Unauthorized
      if (operation.responses['401'] || operation.responses['403']) {
        lines.push('  @contact @api @control-room');
        lines.push(`  Scenario: ${summary} without token leading to 401 or 403`);
        lines.push('    Given the API base URL is configured');
        lines.push('    And no Authorization bearer token');
        lines.push('    And request body is the OpenAPI example for this operation');
        lines.push(`    When request operation is "${method.toUpperCase()}"`);
        lines.push(`    And request path is "${apiPath}"`);
        lines.push('    And the request is sent');
        lines.push('    Then response status is 401 or 403 or 404');
        lines.push('');
      }
    }
  }

  return lines.join('\n').trimEnd() + '\n';
}

function main() {
  if (!fs.existsSync(SPEC_PATH)) {
    console.error(`Spec not found: ${SPEC_PATH}`);
    process.exit(1);
  }

  const oaspec = JSON.parse(fs.readFileSync(SPEC_PATH, 'utf8'));
  const feature = emitFeature(oaspec);

  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  fs.writeFileSync(OUT_PATH, feature, 'utf8');
  console.log(`Wrote ${path.relative(root, OUT_PATH)}`);
}

main();
